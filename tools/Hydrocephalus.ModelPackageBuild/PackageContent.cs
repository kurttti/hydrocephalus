using System.Globalization;
using Hydrocephalus.Inference.Segmentation;

namespace Hydrocephalus.ModelPackageBuild;

/// <summary>
/// Содержимое пакета, не зависящее от конкретного файла весов.
///
/// Лежит в коде, а не в файлах рядом: пакет собирается на машине с весами, и
/// забытый или подменённый шаблон дал бы пакет с неверной карточкой, который
/// проверку целостности при этом прошёл бы.
/// </summary>
internal static class PackageContent
{
    /// <summary>Версия описания предобработки.</summary>
    internal const string PreprocessingVersion = "conform-lia-256-1";

    /// <summary>
    /// Версия карты меток.
    ///
    /// Берётся у самого движка, а не объявляется здесь второй строкой: разойдясь,
    /// два объявления дали бы пакет, который приложение отвергнет как
    /// несовместимый, и причина была бы неочевидна.
    /// </summary>
    internal static readonly string LabelMapVersion = OnnxVentricleSegmentation.LabelMapVersion;

    /// <summary>
    /// Описание предобработки.
    ///
    /// Записано в пакет, а не подразумевается: модель верна только для входа,
    /// приведённого ровно так, и приложение обязано уметь проверить, что его
    /// предобработка та же.
    /// </summary>
    internal const string Preprocessing = """
        {
          "version": "conform-lia-256-1",
          "orientation": "LIA",
          "size": 256,
          "spacingMillimetres": 1.0,
          "intensity": {
            "range": [0, 255],
            "rescale": "robust",
            "highCropFraction": 0.999
          },
          "input": {
            "sliceAxis": 1,
            "sliceStack": 7,
            "transposedInPlane": true,
            "scale": "0..1"
          }
        }
        """;

    /// <summary>
    /// Карта меток: какие классы сети считаются желудочковой системой.
    /// </summary>
    internal const string Labels = """
        {
          "version": "fastsurfer-vinn-axial-2.0.0",
          "source": "FastSurferCNN/config/FastSurfer_ColorLUT.tsv (v2.5.4)",
          "ventricularSystem": {
            "freeSurferLabels": [4, 5, 14, 15, 43, 44],
