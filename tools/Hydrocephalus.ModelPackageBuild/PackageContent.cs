              "III желудочек",
              "IV желудочек",
              "правый боковой желудочек",
              "правый нижний рог"
            ]
          }
        }
        """;

    /// <summary>
    /// Карточка модели: что это, чьё, на чём проверено и где ломается.
    /// </summary>
    /// <param name="modelVersion">Версия модели из манифеста.</param>
    /// <returns>Содержимое `model-card.md`.</returns>
    internal static string ModelCard(string modelVersion) => string.Create(
        CultureInfo.InvariantCulture,
        $$"""
        # Модель сегментации желудочков: {{modelVersion}}

        ## Что это

        Сеть FastSurfer VINN (view-aggregating interpolating network), обученная
        авторами на разметке FreeSurfer. Из её разметки берутся только метки
        желудочковой системы: боковые желудочки с нижними рогами, III и IV.

        **Работает один аксиальный вид из трёх.** Полная модель складывает три вида
        и требует изотропного объёма около миллиметра; в клинической выборке таких
        серий 4 из 26, а 22 — аксиальные T1 толщиной больше 4 мм, где корональный и
        сагиттальный виды собирались бы из срезов, между которыми 5–7 мм пустоты.
        Это **ослабленный режим**, и результат помечается соответственно.

        ## Происхождение и лицензия

        Copyright 2019 Image Analysis Lab, German Center for Neurodegenerative
        Diseases (DZNE), Bonn.

        Код и веса распространяются по Apache License 2.0:
        http://www.apache.org/licenses/LICENSE-2.0

        Веса: Zenodo 10390573, файл `aparc_vinn_axial_v2.0.0.pkl`,
        SHA-256 `81ab25ccbfc432cc41fb6089d11ff2a45b5a88e659092096cb1e067269f806b8`.

        Исходный код: https://github.com/Deep-MI/FastSurfer (версия 2.5.4).

        **Изменения относительно исходных весов.** Веса не переобучались и не
        изменялись. Выполнен перевод из формата PyTorch в ONNX с закреплённым
        единичным коэффициентом масштаба — он допустим потому, что снимок
        приводится к 1 мм до вывода. Разметка сверена с исходной моделью на
        настоящих срезах: метки совпали на всех 1 048 576 отсчётах проверки.

        **Чего здесь нет.** Не используется `recon-surf` и не используется
        FreeSurfer: `notice.txt` FastSurfer относится именно к ним, и собственная
        лицензия FreeSurfer к этому пакету отношения не имеет.

        ## Назначение

        Исследовательское. Авторы FastSurfer оговаривают: «для исследовательских
        целей… не для поддержки клинических решений у отдельного пациента». Решение
        владельца проекта (ADR 0009) это повторяет: результаты модели помечаются
        как непроверенные, пока не пройдена валидация против ручной разметки.

        ## На чём проверено

        Клиническая выборка, 26 серий T1 с покрытием головы:

        - измерено 24, отказов модели 2;
        - там, где измеряет и пороговый метод, пять сверок из шести сошлись в
          пределах 0,013 по индексу Эванса, а на шестой ошибался пороговый метод;
        - перенос в приложение сверен с исследовательским контуром: приведение
          совпало повоксельно, маска по Dice 0,9998, индексы 23 из 24 точно.

        ## Где ломается

        - **Прицельные блоки** (покрытие ≤72 мм): выдаёт бессмысленное число
          вместо отказа. Такие серии отсеиваются до модели.
        - **Низкоконтрастные T1**: один из двух отказов выборки.
        - **Крайняя гидроцефалия**: в сентябре 2026 на серии с желудочками в сотни
          миллилитров разметила 11 мл обрывков височных рогов. Та серия в
          замороженной выборке не нашлась, и риск остаётся **непроверенным** —
          именно в той группе, ради которой модель нужна.

        ## Что обязано ехать вместе с моделью

        Модель верна только для входа, приведённого по `preprocessing.json`:
        куб 256 с шагом 1 мм, укладка LIA, яркость 0–255, стопки по семь соседних
        срезов, срез подаётся транспонированным. При иной раскладке среза модель
        возвращает правдоподобное малое число, а не явную ошибку.
        """);
}
