using Hydrocephalus.Domain.Imaging;

namespace Hydrocephalus.Inference.Segmentation;

/// <summary>
/// Способ получить маску желудочковой системы.
///
/// Договор нужен затем, что способов стало два: пороговый (`baseline`) и
/// обученная модель (ADR 0009). ADR 0002 требует держать инференс за
/// интерфейсом, чтобы вынести его в отдельный процесс без переделки вызывающих,
/// и это тот самый интерфейс.
///
/// Живёт в `Inference`, а не в `Domain`, потому что <see cref="VoxelMask"/>
/// объявлен здесь же. Переносить маску в домен ради расположения договора
/// значило бы тащить за ней сетку, карту меток и разбор решения — работа
/// несоразмерная поводу.
///
/// Реализация обязана **помечать свой результат сама**. Ни один из двух путей не
/// валидирован клинически, и достоверность, выставленная вызывающим, рано или
/// поздно оказалась бы забыта в одном из мест вызова.
/// </summary>
public interface IVentricleSegmentation
{
    /// <summary>
    /// Чем получена маска: код способа вместе с версией.
    ///
    /// Входит в версию определения признака, а не только в журнал: значения,
    /// полученные пороговым методом и моделью, несопоставимы между собой, и в
    /// сводке по группам они не должны смешаться неразличимо.
    /// </summary>
    string Provenance { get; }

    /// <summary>
    /// Размечает объём.
    /// </summary>
    /// <param name="volume">Объём серии.</param>
    /// <param name="weighting">Взвешенность серии.</param>
    /// <param name="pseudonymousSeriesId">
    /// Псевдоним серии, которой принадлежит объём.
    ///
    /// Нужен затем, что одну и ту же серию размечают дважды — для экрана и для
    /// отчёта, — а моделью это минута счёта на каждый раз. По псевдониму
    /// <see cref="CachingVentricleSegmentation"/> узнаёт, что отвечать нечего:
    /// ответ уже есть. Сами реализации его не используют, и это нормально.
    /// Псевдоним здесь не исключение в слое: источник объёмов принимает его так
    /// же и по той же причине.
    /// </param>
    /// <param name="cancellationToken">Токен отмены.</param>
    /// <returns>Маска с замечаниями и достоверностью; при отказе маска пуста.</returns>
    VentricleSegmentationResult Segment(
        IVoxelVolume volume,
        SeriesWeighting weighting,
        string pseudonymousSeriesId,
        CancellationToken cancellationToken = default);
}
