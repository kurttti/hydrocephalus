namespace Hydrocephalus.Infrastructure.Dicom;

/// <summary>
/// Причина, по которой файл не принят. Каждое исключение получает машинно-читаемый код
/// и человекочитаемое объяснение (docs/data/README.md); текст формируется на слое
/// представления, здесь хранится только код.
/// </summary>
public enum ImportRejectionCode
{
    /// <summary>Код не задан.</summary>
    Unspecified = 0,

    /// <summary>Файл не является DICOM или заголовок повреждён.</summary>
    NotADicomFile = 1,

    /// <summary>Файл превышает допустимый размер.</summary>
    FileTooLarge = 2,

    /// <summary>Каталог вложен глубже допустимого.</summary>
    DirectoryTooDeep = 3,

    /// <summary>Превышено допустимое число файлов за один импорт.</summary>
    TooManyFiles = 4,

    /// <summary>Разбор файла завершился ошибкой.</summary>
    UnreadableDataset = 5,

    /// <summary>В файле отсутствует SeriesInstanceUID, группировка невозможна.</summary>
    MissingSeriesIdentifier = 6,

    /// <summary>
    /// Файл повторяет уже принятый экземпляр: тот же SOPInstanceUID.
    /// В реальных выгрузках одна и та же серия нередко лежит в двух местах,
    /// и без этой проверки повтор читался бы как второй набор срезов.
    /// </summary>
    DuplicateInstance = 7,

    /// <summary>
    /// Файл — не снимок: пикселей в нём нет.
    ///
    /// Выгрузки содержат служебные объекты рядом со срезами: настройки просмотра
    /// (Grayscale Softcopy Presentation State), протоколы, структурированные
    /// отчёты. Каждый лежит в собственной серии, и без этой проверки такая серия
    /// попадала бы в исследование как набор срезов размером 0 на 0.
    /// </summary>
    NotAnImage = 8,

    /// <summary>
    /// Снимок сделан не магнитным резонансом.
    ///
    /// Выборка содержит компьютерную томографию: три папки иНТГ и одна в
    /// `Для А.В. Станишевского` (docs/data/README.md). Решением владельца данных
    /// от 2026-09-28 ориентир только на МРТ, поэтому КТ отклоняется здесь, на
    /// входе и с названной причиной. Прежде она проходила молча: распознавание
    /// взвешенности читает теги импульсной последовательности, которых у КТ нет,
    /// серия получала `Unknown`, папка выглядела принятой, а измерения не было.
    ///
    /// Отсутствующая модальность не отклоняется: пустой тег означает неполный
    /// экспорт, а не другой аппарат, и терять из-за него снимок МРТ нельзя.
    /// </summary>
    NotMagneticResonance = 9,

    /// <summary>
    /// Снимок не головы: объявленная область съёмки не головная.
    ///
    /// Цель исследования — головной мозг, и снимок живота или позвоночника
    /// разбирать незачем. Без этой проверки абдоминальная МРТ принималась как
    /// `Baseline/T1` и отвергалась лишь сегментацией, с причиной «желудочки
    /// неправдоподобно малы»: формально верной, по существу вводящей в
    /// заблуждение — желудочков в животе нет.
    ///
    /// Отсутствующая область не отклоняется: в наборе тег пуст у 312 серий из
    /// 385, и отклонять по пустому значило бы потерять почти всё.
    /// </summary>
    NotHead = 10,
}

/// <summary>
/// Отклонённый файл.
///
/// Путь к файлу намеренно не сохраняется: в исходном сборе данных имена файлов и папок
/// содержат фамилии пациентов (docs/data/README.md), поэтому попадание пути в журнал
/// было бы утечкой PHI. Вместо него используется устойчивая непрозрачная ссылка.
/// </summary>
/// <param name="Code">Машинно-читаемый код отказа.</param>
/// <param name="OpaqueFileReference">Псевдонимная ссылка на файл для корреляции.</param>
public readonly record struct ImportRejection(ImportRejectionCode Code, string OpaqueFileReference);
