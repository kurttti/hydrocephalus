using Hydrocephalus.Domain.Imaging;

namespace Hydrocephalus.Domain.Reporting;

/// <summary>
/// Серия, по которой составлен отчёт.
///
/// ADR 0005 требует псевдонимных идентификаторов серий в каноническом слое с
/// самого начала, и до версии схемы 1.2.0 этого требования отчёт не выполнял:
/// он назывался по исследованию и о серии молчал. Пока измерение было одно и
/// шло по той серии, которую выбрало ранжирование, умолчание ничего не стоило.
/// С появлением ручного угла мозолистого тела оно стало ошибкой: угол меряется
/// на корональной серии, а для анализа выбирается аксиальная, то есть в одном
/// исследовании рядом лежат версии отчёта по разным сериям — и различить их
/// было нечем.
///
/// Полей четыре, и каждое отвечает на вопрос, который иначе требует повторного
/// обхода набора:
///
/// - **идентификатор** — единственное устойчивое имя серии (своего у неё нет) и
///   ключ сведения с описью набора;
/// - **взвешенность** — по ней сегментация выбирает направление порога, и на
///   FLAIR пороговый путь ошибается примерно в двух случаях из семи
///   (docs/roadmap.md). Значение, полученное по T1 и по FLAIR, без этого поля
///   в сводке неразличимо;
/// - **плоскость** — индекс Эванса определён на аксиальной, угол мозолистого
///   тела на корональной. Измерение, о плоскости которого отчёт молчит,
///   проверить нельзя;
/// - **уровень входа** — автоматический индекс требует объёмной серии, ручной
///   нет, и по этому полю видно, какой из двух путей был вообще возможен.
///
/// Геометрии здесь нет намеренно: канонический слой — результат анализа, а не
/// копия описания серии из DICOM.
/// </summary>
public sealed record AnalysedSeries
{
    /// <summary>Псевдонимный идентификатор серии.</summary>
    public required string PseudonymousSeriesId { get; init; }

    /// <summary>Тип взвешенности.</summary>
    public required SeriesWeighting Weighting { get; init; }

    /// <summary>Плоскость получения.</summary>
    public required ImagingPlane Plane { get; init; }

    /// <summary>Уровень входа.</summary>
    public required AcquisitionTier Tier { get; init; }

    /// <summary>
    /// Описывает серию для отчёта.
    /// </summary>
    /// <param name="series">Серия рабочей копии.</param>
    /// <returns>Запись отчёта о серии.</returns>
    public static AnalysedSeries Of(ImagingSeries series)
    {
        ArgumentNullException.ThrowIfNull(series);

        return new AnalysedSeries
        {
            PseudonymousSeriesId = series.PseudonymousSeriesId,
            Weighting = series.Weighting,
            Plane = series.Geometry.Plane,
            Tier = series.Tier,
        };
    }
}
