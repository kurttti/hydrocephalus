using Hydrocephalus.Domain.Quality;

namespace Hydrocephalus.Domain.Measurements;

/// <summary>
/// Причина, по которой измерение не получено.
///
/// Отдельна от <c>RefusalCode</c> намеренно: тот описывает
/// отказ **классификации**, и в выборке 56 отчётов из 57 несут
/// `ModelPackageUnusable` рядом с посчитанным индексом. Сложить сюда причины
/// измерения значило бы сделать оба поля нечитаемыми.
///
/// Коды сохраняются **по имени**: отчёты на диске переживают сборку, и
/// переименование члена превратит прошлые отчёты в нечитаемые. Добавлять новые
/// можно, переименовывать и перенумеровывать существующие — нет.
/// </summary>
public enum MeasurementRefusal
{
    /// <summary>Причина не названа.</summary>
    Unspecified = 0,

    /// <summary>
    /// Взвешенность серии не распознана. Сегментация выбирает по ней
    /// направление порога, и угадывание выделило бы ткань вместо ликвора.
    /// </summary>
    WeightingNotRecognised = 1,

    /// <summary>Объём не похож на голову: разбирать нечего.</summary>
    NotAHead = 2,

    /// <summary>
    /// Серию не удалось прочитать: неподдерживаемый формат пикселей,
    /// сжатый синтаксис, нарушенное правило домена.
    /// </summary>
    SeriesUnreadable = 3,

    /// <summary>Сегментация отказала: выводить измерение не из чего.</summary>
    SegmentationRefused = 4,

    /// <summary>
    /// Взвешенность, на которой метод не определён: внутренняя пластинка
    /// черепа ищется по тёмной полосе «ликвор и кость», а на T2 она не тёмная.
    /// </summary>
    WeightingNotSupported = 5,

    /// <summary>Оси сетки не совпадают с осями пациента настолько, чтобы найти аксиальную плоскость.</summary>
    AxesNotAligned = 6,

    /// <summary>В маске нет передних рогов по обе стороны от средней линии.</summary>
    FrontalHornsNotFound = 7,

    /// <summary>На плоскости рогов не нашлась граница мозга и черепа.</summary>
    InnerSkullNotFound = 8,
}

/// <summary>
/// Попытка измерения: чем размечали, что из этого вышло и почему измерения нет.
///
/// Появилась потому, что отчёт неизмеренного исследования не говорил ничего:
/// `segmentation: null`, пустые признаки — и всё. Причину дважды приходилось
/// доставать временной правкой кода (разборы `t2-flair-2026-10-09.md` и
/// `четыре-t1-2026-10-09.md`), а врачу она не доставалась никак.
///
/// Второе назначение — различать способы разметки. Договор
/// <c>IVentricleSegmentation</c> требует, чтобы значения, полученные порогом и
/// моделью, не смешивались неразличимо; до появления этой записи в отчёте
/// стояла таблица маршрутизации целиком, по которой выбранную ветвь было
/// не восстановить.
/// </summary>
public sealed record MeasurementAttempt
{
    /// <summary>
    /// Чем получена маска: код способа с версией, как его называет сама
    /// реализация. Пусто, если до сегментации не дошло.
    /// </summary>
    public string LabelMapVersion { get; init; } = string.Empty;

    /// <summary>
    /// Достоверность, которой сегментация пометила свою маску.
    /// </summary>
    public MeasurementQuality MaskQuality { get; init; } = MeasurementQuality.Unreliable;

    /// <summary>
    /// Замечания сегментации к маске вместе с их параметрами: именно они
    /// называют, чем маска не подошла.
    /// </summary>
    public IReadOnlyList<QualityIssue> SegmentationIssues { get; init; } = [];

    /// <summary>
    /// Почему измерения нет; <see langword="null"/>, если оно получено.
    /// </summary>
    public MeasurementRefusal? Refusal { get; init; }
}
