namespace Hydrocephalus.Domain.Access;

/// <summary>
/// Право на отдельную операцию.
///
/// Проверяется право, а не роль. Роль отвечает на вопрос «кто это», право —
/// «что ему можно», и только второе относится к делу в точке вызова. Если
/// сценарии сверяются с ролями напрямую, политика доступа расползается по коду
/// и меняется в нескольких местах сразу — а расходятся такие места молча.
/// </summary>
public enum Capability
{
    /// <summary>Право не задано.</summary>
    Unspecified = 0,

    /// <summary>Запуск анализа исследования.</summary>
    AnalyseStudy = 1,

    /// <summary>
    /// Экспорт обезличенного отчёта: только псевдонимные идентификаторы.
    /// Пригоден для передачи и разбора случаев (ADR 0005).
    /// </summary>
    ExportDeidentifiedReport = 2,

    /// <summary>
    /// Экспорт клинического отчёта с идентификаторами пациента,
    /// восстанавливаемыми из внешнего защищённого реестра (ADR 0005).
    /// </summary>
    ExportClinicalReport = 3,

    /// <summary>
    /// Экспорт манифеста датасета в исследовательский контур.
    /// Описывает состав выборки и покидает клинический контур.
    /// </summary>
    ExportDatasetManifest = 4,

    /// <summary>
    /// Чтение журнала аудита.
    ///
    /// Отдельное право, а не следствие любого другого: журнал показывает, кто
    /// и что делал со всеми исследованиями установки, и доступ к нему не
    /// вытекает из права работать с одним из них. Данных пациента журнал
    /// не содержит — только псевдонимы и коды, — поэтому право относится
    /// к обслуживанию установки, а не к клинической работе.
    /// </summary>
    ReadAuditLog = 5,
}
