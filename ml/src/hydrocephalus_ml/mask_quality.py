"""Проверка маски мозга до того, как на ней что-то измерят.

Все известные отказы выравнивания по AC–PC оказались дефектами входа, а не
метода: снимок, на котором голова не поместилась в кадр; блок из семидесяти
срезов вместо головы; маска, собравшая разрозненные куски не-мозга. Ни один из
них не требовал разбора самого выравнивания — все видны по объёму маски и её
габаритному прямоугольнику, то есть двумя числами вместо шести регистраций.

Проверка согласия нескольких стартов регистрации проверялась отдельно и
отвергнута: расхождение стартов не предсказывает ошибку (при расхождении 10,04°
ошибка была 0,32°, при нулевом расхождении — 1,37°). Сторожить нужно вход.

Границы взяты из измерения 71 маски (IXI и AFIDs) и семи клинических серий, а не
назначены. Между худшим годным случаем и лучшим негодным есть промежуток, и
порог поставлен в него, но промежуток узкий: 810 мл против 955. Это оценка по
имеющимся данным, а не проверенная граница.
"""

from __future__ import annotations

from typing import NamedTuple

__all__ = [
    "MAXIMUM_BRAIN_MILLILITRES",
    "MINIMUM_BRAIN_MILLILITRES",
    "MaskProblem",
    "inspect_mask",
]

# Объём размеченного мозга. Нижняя граница отделяет 810 мл обрезанного снимка от
# 955 мл (пятый процентиль нормы) и 965 мл худшей годной клинической серии.
MINIMUM_BRAIN_MILLILITRES = 900.0
MAXIMUM_BRAIN_MILLILITRES = 1700.0

# Габариты по осям приведённого объёма: поперёк, спереди назад, сверху вниз.
# Измеренный размах — 123–148, 119–149 и 143–186 мм; границы взяты с запасом,
# потому что здесь ловится не размер мозга, а маска, не являющаяся мозгом.
EXTENT_LIMITS_MILLIMETRES = ((115.0, 160.0), (115.0, 160.0), (135.0, 195.0))

_AXIS_NAMES = ("поперёк", "спереди назад", "сверху вниз")


class MaskProblem(NamedTuple):
    """Причина отказа: код для разбора и пояснение для человека."""

    code: str
    explanation: str


def inspect_mask(
    millilitres: float,
    extent_millimetres: tuple[float, float, float],
) -> MaskProblem | None:
    """Проверяет маску мозга. Возвращает причину отказа либо ``None``.

    Отказ здесь лучше измерения: неверная плоскость AC–PC не выглядит неверной,
    и посчитанный на ней угол мозолистого тела подаётся как достоверный.
    """
    if len(extent_millimetres) != 3:
        raise ValueError("Габариты задаются тремя числами.")

    if millilitres < MINIMUM_BRAIN_MILLILITRES:
        return MaskProblem(
            "brainMaskTooSmall",
            f"размеченного мозга {millilitres:.0f} мл при ожидаемых "
            f"от {MINIMUM_BRAIN_MILLILITRES:.0f} — снимок обрезан или "
            f"сегментация захватила не весь мозг",
        )

    if millilitres > MAXIMUM_BRAIN_MILLILITRES:
        return MaskProblem(
            "brainMaskTooLarge",
            f"размеченного мозга {millilitres:.0f} мл при ожидаемых "
            f"до {MAXIMUM_BRAIN_MILLILITRES:.0f} — в маску попало не только вещество мозга",
        )

    for axis, (extent, (low, high)) in enumerate(
        zip(extent_millimetres, EXTENT_LIMITS_MILLIMETRES, strict=True)
    ):
        if not low <= extent <= high:
            return MaskProblem(
                "brainMaskExtentImplausible",
                f"размер маски {_AXIS_NAMES[axis]} {extent:.0f} мм вне "
                f"правдоподобных {low:.0f}–{high:.0f} — это не целый мозг",
            )

    return None
