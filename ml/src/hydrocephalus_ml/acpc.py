"""Приведение объёма к системе координат AC–PC.

Все показатели из `docs/ml/README.md` — угол мозолистого тела, срез индекса
Эванса, границы областей qDESH — задаются относительно линии между передней и
задней спайками. Кадр получают выравниванием снимка к шаблону ICBM152 2009c.

**Шаблон при этом не выровнен по AC–PC.** По разметке AFIDs на самом шаблоне
линия спаек наклонена к его горизонтали примерно на пять с половиной градусов, а
передняя спайка лежит на 2,7 мм ниже задней. Кадр, унаследованный от шаблона без
поправки, повёрнут на ту же величину — воспроизводимо, что и делает ошибку
опасной: она не проявляется ни в разбросе, ни в повторных измерениях, а в
литературе отклонение 5–10° названо клинически значимым для угла мозолистого
тела.

Поправка выводится здесь из координат спаек, а не записана константой: при смене
шаблона (у AFIDs размечено четырнадцать) она пересчитается сама.

Модуль намеренно обходится стандартной библиотекой: регистрация к шаблону живёт
в исследовательском контуре и тянет SimpleITK, а геометрия кадра — нет, и она
должна проверяться в CI без данных и без ML-стека.
"""

from __future__ import annotations

import math
from typing import NamedTuple

__all__ = [
    "ICBM152_2009C_AC",
    "ICBM152_2009C_PC",
    "Point",
    "commissural_pitch",
    "level_commissures",
    "rotate_about_left_right_axis",
]


class Point(NamedTuple):
    """Точка в миллиметрах. Оси — как в разметке AFIDs: RAS."""

    x: float
    y: float
    z: float


# Эталонная разметка AFIDs на tpl-MNI152NLin2009cAsym (репозиторий
# github.com/afids/tpl-MNI152NLin2009cAsym, ветка master, лицензия MNI/Collins —
# разрешительная). Четыре независимых эксперта на том же шаблоне дают наклон от
# -3,81° до -7,76°, то есть сам ориентир известен с точностью около ±2°: это
# согласуется с опубликованной точностью постановки точек 0,5–1 мм, потому что
# миллиметр на конце линии длиной 28 мм и есть два градуса.
ICBM152_2009C_AC = Point(-0.204861407692308, 2.72288076923077, -4.88105282051282)
ICBM152_2009C_PC = Point(-0.00726026948717949, -25.0450538461538, -2.21068230769231)


def commissural_pitch(ac: Point, pc: Point) -> float:
    """Наклон линии спаек к горизонтали кадра, в градусах.

    В истинном кадре AC–PC он равен нулю по определению. Положительное значение
    означает, что передняя спайка выше задней.
    """
    dx, dy, dz = ac.x - pc.x, ac.y - pc.y, ac.z - pc.z
    length = math.sqrt(dx * dx + dy * dy + dz * dz)

    if length == 0.0:
        raise ValueError("Спайки не могут совпадать: линия не определена.")

    return math.degrees(math.asin(dz / length))


def rotate_about_left_right_axis(point: Point, degrees: float, centre: Point) -> Point:
    """Поворот по тангажу вокруг оси «влево-вправо», проходящей через centre."""
    angle = math.radians(degrees)
    cos, sin = math.cos(angle), math.sin(angle)
    y, z = point.y - centre.y, point.z - centre.z

    return Point(
        point.x,
        centre.y + y * cos - z * sin,
        centre.z + y * sin + z * cos,
    )


def level_commissures(ac: Point, pc: Point) -> float:
    """Доворот, выпрямляющий линию спаек, в градусах.

    Знак здесь не предмет соглашения: на эту величину нужно повернуть кадр,
    чтобы наклон стал нулевым, и результат проверяется на самих точках.
    """
    # Угол берётся в плоскости «вперёд-вверх», а не из наклона линии к
    # горизонтали: поворот вокруг оси «влево-вправо» не трогает поперечную
    # составляющую, и она не должна входить в длину, по которой считается угол.
    # Спайки лежат в долях миллиметра от средней линии, так что разница мала, но
    # с ней проверка ниже никогда не сойдётся точно.
    correction = math.degrees(math.atan2(pc.z - ac.z, ac.y - pc.y))
    levelled = rotate_about_left_right_axis(pc, correction, centre=ac)

    # Проверка вместо доверия к выкладке: поворот вокруг оси «влево-вправо» не
    # трогает x, поэтому наклон обязан обнуляться точно.
    residual = commissural_pitch(ac, levelled)
    if abs(residual) > 1e-9:
        raise ArithmeticError(
            f"Доворот на {correction:.4f}° оставил наклон {residual:.6f}°."
        )

    return correction
